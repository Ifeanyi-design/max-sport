/**
 * Normalizes competition name or slug and returns direct HD badge.
 */
export function getCompetitionDictionaryLogo(slugOrName?: string | null): string | null {
  if (!slugOrName) return null;
  const unaccented = slugOrName
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();

  const key = unaccented.replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

  if (COMPETITION_LOGOS[key]) return COMPETITION_LOGOS[key];
  if (COMPETITION_LOGOS[unaccented]) return COMPETITION_LOGOS[unaccented];

  // Try matching without "football", "league", "cup"
  const stripped = key
    .replace(/-football|-league|-cup|-premier|-division|-division-n|-division-1/g, "")
    .replace(/^-+|-+$/g, "");

  for (const [k, url] of Object.entries(COMPETITION_LOGOS)) {
    if (k === stripped || k.includes(stripped) || (stripped.length > 4 && stripped.includes(k))) {
      return url;
    }
  }

  return null;
}
